import type { ExperimentContent } from "@/lib/content/types";

export interface ReportMeasurement {
  title: string;
  columns: string[];
  rows: string[][];
  provenance: "actual" | "simulated" | "mixed";
  note?: string;
}

export interface ReportInput {
  content: ExperimentContent;
  studentName: string;
  date: string;
  objectives: string;
  apparatus: string;
  procedureNotes: string;
  measurements: ReportMeasurement[];
  calculations: string;
  uncertainties: string;
  errors: string;
  conclusion: string;
}

const PROVENANCE_TEXT: Record<ReportMeasurement["provenance"], string> = {
  actual: "Actual laboratory measurement recorded by the student.",
  simulated: "Simulated measurement generated by the platform model — NOT laboratory data.",
  mixed: "Mixed dataset: contains both simulated and laboratory values. Verify each row before submission."
};

export function buildMarkdownReport(input: ReportInput): string {
  const { content } = input;
  const lines: string[] = [];
  lines.push(`# ${content.title} — Laboratory Report`);
  lines.push("");
  lines.push(`**Student:** ${input.studentName || "________________"}  `);
  lines.push(`**Date:** ${input.date}  `);
  lines.push(`**Experiment:** ${content.number} · ${content.title}  `);
  lines.push(`**Kit:** ${content.kit.name} (${content.kit.verification})`);
  lines.push("");
  lines.push("## Objectives");
  lines.push(input.objectives || content.objectives.map((o) => `- ${o}`).join("\n"));
  lines.push("");
  lines.push("## Apparatus");
  lines.push(input.apparatus || content.hardware.map((h) => `- ${h.itemId}`).join("\n"));
  lines.push("");
  lines.push("## Procedure");
  lines.push(input.procedureNotes || content.procedure.map((p) => `### ${p.title}\n${p.steps.map((s) => `- ${s.title}: ${s.detail}`).join("\n")}`).join("\n\n"));
  lines.push("");
  for (const m of input.measurements) {
    lines.push(`## ${m.title}`);
    lines.push(`_${PROVENANCE_TEXT[m.provenance]}_`);
    if (m.note) lines.push(m.note);
    lines.push("");
    lines.push(`| ${m.columns.join(" | ")} |`);
    lines.push(`| ${m.columns.map(() => "---").join(" | ")} |`);
    for (const row of m.rows) lines.push(`| ${row.join(" | ")} |`);
    lines.push("");
  }
  lines.push("## Calculations and analysis");
  lines.push(input.calculations || "_To be completed._");
  lines.push("");
  lines.push("## Uncertainty budget");
  lines.push(input.uncertainties || "_To be completed._");
  lines.push("");
  lines.push("## Sources of error");
  lines.push(input.errors || content.errors.map((e) => `- **${e.source}** (${e.type}): ${e.effect} Mitigation: ${e.mitigation}`).join("\n"));
  lines.push("");
  lines.push("## Conclusion");
  lines.push(input.conclusion || "_To be completed._");
  lines.push("");
  lines.push("---");
  lines.push("Generated by the Quantum Optics Laboratory. Simulated values are labelled as such; no measurement has been invented on the student's behalf.");
  return lines.join("\n");
}

export function buildHtmlReport(input: ReportInput): string {
  const { content } = input;
  const esc = (s: string) =>
    s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  const tables = input.measurements
    .map(
      (m) => `
      <h2>${esc(m.title)}</h2>
      <p class="prov ${m.provenance}">${esc(PROVENANCE_TEXT[m.provenance])}</p>
      ${m.note ? `<p>${esc(m.note)}</p>` : ""}
      <table><thead><tr>${m.columns.map((c) => `<th>${esc(c)}</th>`).join("")}</tr></thead>
      <tbody>${m.rows.map((r) => `<tr>${r.map((c) => `<td>${esc(c)}</td>`).join("")}</tr>`).join("")}</tbody></table>`
    )
    .join("");

  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><title>${esc(content.title)} — Laboratory Report</title>
<style>
  @page { size: A4; margin: 18mm; }
  body { font-family: Georgia, "Times New Roman", serif; color:#171713; line-height:1.55; max-width: 760px; margin: 32px auto; padding: 0 24px; }
  h1 { font-size: 26px; margin: 0 0 4px; font-weight: 500; }
  h2 { font-size: 15px; text-transform: uppercase; letter-spacing: .08em; border-top: 1px solid #bbb; padding-top: 10px; margin-top: 26px; }
  .meta { font-family: ui-monospace, monospace; font-size: 11px; color:#555; margin-bottom: 24px; }
  .prov { font-size: 11px; padding: 6px 8px; border-left: 2px solid #999; background:#f4f2ec; }
  .prov.actual { border-color:#14524A; }
  .prov.simulated { border-color:#B23A1E; }
  table { width:100%; border-collapse: collapse; font-size: 11px; margin: 10px 0 20px; }
  th, td { border-bottom: 1px solid #ddd; padding: 5px 6px; text-align: left; }
  th { border-bottom: 1px solid #171713; font-family: ui-monospace, monospace; font-size: 10px; text-transform: uppercase; }
  pre { white-space: pre-wrap; font-family: ui-monospace, monospace; font-size: 11px; background:#f6f4ee; padding: 10px; }
  footer { margin-top: 32px; border-top:1px solid #bbb; padding-top: 8px; font-size: 9px; color:#666; }
</style></head><body>
<h1>${esc(content.title)}</h1>
<div class="meta">Student: ${esc(input.studentName || "________________")} · Date: ${esc(input.date)} · Experiment ${esc(content.number)}<br>
Kit: ${esc(content.kit.name)} (${esc(content.kit.verification)})</div>
<h2>Objectives</h2><p>${esc(input.objectives || content.objectives.join(" "))}</p>
<h2>Apparatus</h2><p>${esc(input.apparatus || content.hardware.map((h) => h.itemId).join(", "))}</p>
<h2>Procedure</h2><p>${esc(input.procedureNotes || content.procedure.map((p) => p.title).join("; "))}</p>
${tables}
<h2>Calculations and analysis</h2><pre>${esc(input.calculations || "To be completed.")}</pre>
<h2>Uncertainty budget</h2><pre>${esc(input.uncertainties || "To be completed.")}</pre>
<h2>Sources of error</h2><p>${esc(input.errors || content.errors.map((e) => `${e.source}: ${e.effect}`).join(" "))}</p>
<h2>Conclusion</h2><p>${esc(input.conclusion || "To be completed.")}</p>
<footer>Generated by the Quantum Optics Laboratory. Simulated values are labelled; no measurement is fabricated.</footer>
</body></html>`;
}

export function downloadReportHtml(input: ReportInput, filename: string): void {
  if (typeof window === "undefined") return;
  const blob = new Blob([buildHtmlReport(input)], { type: "text/html;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename.endsWith(".html") ? filename : `${filename}.html`;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function printReport(input: ReportInput): void {
  if (typeof window === "undefined") return;
  const w = window.open("", "_blank", "noopener,noreferrer");
  if (!w) {
    downloadReportHtml(input, "laboratory-report.html");
    return;
  }
  w.document.write(buildHtmlReport(input));
  w.document.close();
  w.focus();
  setTimeout(() => w.print(), 350);
}
